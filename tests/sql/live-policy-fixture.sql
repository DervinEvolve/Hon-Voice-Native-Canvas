-- Canvas history: the live layout has canvas_history_events and
-- canvas_history_snapshots with uuid user_id, and no canvas_history table.
-- tests/sql/live-policy-legacy-canvas.sql adds canvas_history for the
-- legacy layout; tests/sql/live-policy-no-canvas.sql removes both tables.
CREATE TABLE IF NOT EXISTS public.canvas_history_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id text NOT NULL,
  user_id uuid,
  wallet_address text,
  event_type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.canvas_history_snapshots (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id text NOT NULL,
  user_id uuid,
  wallet_address text,
  canvas_state jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
-- commentService.ts writes 'guest-user' and Supabase user IDs, so user_id is text.
CREATE TABLE IF NOT EXISTS public.comment_votes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  comment_id uuid NOT NULL,
  user_id text NOT NULL,
  vote_type integer NOT NULL CHECK (vote_type IN (-1, 1)),
  UNIQUE (comment_id, user_id)
);
-- ProfileV2.tsx writes wallet addresses and user IDs, so both columns are text.
CREATE TABLE IF NOT EXISTS public.subscriptions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  subscriber_id text NOT NULL,
  creator_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (subscriber_id, creator_id)
);

